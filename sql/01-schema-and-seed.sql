-- Seed data for the Project Operations Agent demo.
-- Every row here exists to make one demo scenario real. Do not "clean up" the
-- odd-looking values: the injection payload and the PII string are load-bearing,
-- and Zeus exists only to be refused.

DROP TABLE IF EXISTS audit_log CASCADE;
DROP TABLE IF EXISTS status_updates CASCADE;
DROP TABLE IF EXISTS velocity_history CASCADE;
DROP TABLE IF EXISTS sprint_items CASCADE;
DROP TABLE IF EXISTS team_members CASCADE;
DROP TABLE IF EXISTS projects CASCADE;

CREATE TABLE projects (
    key         TEXT PRIMARY KEY,
    name        TEXT NOT NULL,
    in_scope    BOOLEAN NOT NULL  -- the agent is authorized against it
);

CREATE TABLE team_members (
    id           INTEGER PRIMARY KEY,
    project_key  TEXT NOT NULL REFERENCES projects(key),
    name         TEXT NOT NULL,
    capacity_pts INTEGER NOT NULL,
    assigned_pts INTEGER NOT NULL
);

CREATE TABLE sprint_items (
    id            INTEGER PRIMARY KEY,
    project_key   TEXT NOT NULL REFERENCES projects(key),
    title         TEXT NOT NULL,
    description   TEXT NOT NULL DEFAULT '',
    status        TEXT NOT NULL,       -- todo | in_progress | blocked | done
    points        INTEGER NOT NULL,
    assignee_id   INTEGER REFERENCES team_members(id),
    days_in_status INTEGER NOT NULL
);

CREATE TABLE velocity_history (
    project_key     TEXT NOT NULL REFERENCES projects(key),
    sprint          TEXT NOT NULL,
    committed_pts   INTEGER NOT NULL,
    completed_pts   INTEGER NOT NULL
);

-- Where the write action lands, so it is independently verifiable.
CREATE TABLE status_updates (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key TEXT NOT NULL REFERENCES projects(key),
    body        TEXT NOT NULL,
    posted_at   TEXT NOT NULL
);

-- Append-only audit. Deliberately independent of the trace store:
-- the write action depends on being able to answer "what did it do, who authorized
-- it, can we prove it" without asking the agent or the observability backend.
CREATE TABLE audit_log (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor         TEXT NOT NULL,        -- the validated agent identity
    action        TEXT NOT NULL,        -- the tool name
    arguments     JSONB NOT NULL,
    policy_result TEXT NOT NULL,        -- allowed | denied | approval_required
    policy_rule   TEXT NOT NULL,        -- which check decided
    approver      TEXT,                 -- null unless a human decided
    trace_id      TEXT NOT NULL,        -- correlates to the trace store
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX audit_log_trace_idx ON audit_log (trace_id);

